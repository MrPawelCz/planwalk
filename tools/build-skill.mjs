#!/usr/bin/env node
// Builds the self-contained agent skill from the sources, so skill/planwalk can be copied anywhere and still works
// (docs/SPEC.md section 7). Run it through `npm run build:skill`, which rebuilds dist/ first.
//   node tools/build-skill.mjs [--out DIR]        (DIR defaults to skill/planwalk)
//   scripts/validate.mjs   tools/validate.mjs with src/core/ bundled into one file (esbuild, not minified, no dependencies)
//   scripts/capture.mjs    tools/capture.mjs, unchanged
//   assets/planwalk.html   dist/planwalk-empty.html, unchanged (the viewer without sample plans)
// These three files are generated: never edit them by hand. tests/skill/bundle.test.mjs fails when one of them differs from a fresh build.
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const outIdx = args.indexOf('--out');
if (args.length !== (outIdx < 0 ? 0 : 2) || (outIdx >= 0 && !args[outIdx + 1])) {
  console.error('usage: node tools/build-skill.mjs [--out DIR]');
  process.exit(2);
}
const out = resolve(outIdx < 0 ? join(root, 'skill/planwalk') : args[outIdx + 1]);

const viewer = join(root, 'dist/planwalk-empty.html');
if (!existsSync(viewer)) {
  console.error('dist/planwalk-empty.html is missing: run npm run build:skill (it runs npm run build first).');
  process.exit(2);
}

const validator = await build({
  absWorkingDir: root, // the module path comments in the bundle must not depend on where the command is run from
  entryPoints: [join(root, 'tools/validate.mjs')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  write: false,
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: '// Generated by npm run build:skill from tools/validate.mjs and src/core/. Do not edit by hand.' },
});

const files = {
  'scripts/validate.mjs': validator.outputFiles[0].contents,
  'scripts/capture.mjs': readFileSync(join(root, 'tools/capture.mjs')),
  'assets/planwalk.html': readFileSync(viewer),
};
for (const [rel, data] of Object.entries(files)) {
  mkdirSync(dirname(join(out, rel)), { recursive: true });
  writeFileSync(join(out, rel), data);
  console.log(`${rel} ${Math.round(data.length / 1024)} KB`);
}
